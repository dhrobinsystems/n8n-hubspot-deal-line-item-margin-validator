function codeNode(id, name, jsCode, position, mode) {
  return {
    parameters: Object.assign(mode === 'all' ? {} : { mode: 'runOnceForEachItem' }, { jsCode: jsCode }),
    id: id,
    name: name,
    type: 'n8n-nodes-base.code',
    typeVersion: 2,
    position: position
  };
}

function ifNode(id, name, leftValue, position) {
  return {
    parameters: {
      conditions: {
        options: { caseSensitive: true, leftValue: '', typeValidation: 'strict' },
        conditions: [{ id: id + '-c1', leftValue: leftValue, rightValue: true, operator: { type: 'boolean', operation: 'true', singleValue: true } }],
        combinator: 'and'
      },
      options: {}
    },
    id: id,
    name: name,
    type: 'n8n-nodes-base.if',
    typeVersion: 2,
    position: position
  };
}

function hubspotNode(id, name, method, url, position, extra) {
  const e = extra || {};
  const params = {
    method: method,
    url: url,
    authentication: 'predefinedCredentialType',
    nodeCredentialType: 'hubspotAppToken',
    options: Object.assign({}, e.options || {})
  };
  if (e.body) {
    params.sendBody = true;
    params.specifyBody = 'json';
    params.jsonBody = e.body;
  }
  if (e.fullResponse) params.options.response = { response: { fullResponse: true, neverError: true } };
  const node = {
    parameters: params,
    id: id,
    name: name,
    type: 'n8n-nodes-base.httpRequest',
    typeVersion: 4.2,
    position: position,
    credentials: HUBSPOT_CREDENTIAL
  };
  if (e.retry) { node.retryOnFail = true; node.maxTries = 3; node.waitBetweenTries = 2000; }
  if (e.onError) node.onError = e.onError;
  return node;
}

function plainPostNode(id, name, url, body, position) {
  return {
    parameters: {
      method: 'POST',
      url: url,
      sendBody: true,
      specifyBody: 'json',
      jsonBody: body,
      options: { timeout: 10000, response: { response: { fullResponse: true, neverError: true } } }
    },
    id: id,
    name: name,
    type: 'n8n-nodes-base.httpRequest',
    typeVersion: 4.2,
    position: position,
    onError: 'continueRegularOutput'
  };
}

