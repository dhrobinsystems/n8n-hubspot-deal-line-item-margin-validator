/**
 * build-workflow.js
 *
 * Generates workflow.json from the single source of truth in src/. The
 * n8n-core:config and n8n-core:margin regions are copied verbatim into the
 * Code nodes, so the n8n workflow and the Node.js mirror cannot drift apart.
 *
 *   npm run build:workflow   rewrite workflow.json
 *   npm run check:workflow   fail if workflow.json is out of date
 */

