const VERIFY_CODE = code('Verify & Extract: signature check, config, margin rules, and deal extraction.', `
const EXAMPLE_RULES = ${EXAMPLE_RULES};
const input = $input.first();
const read = readEnv();
const env = read.env;
const rawHeaders = (input.json && input.json.headers) || {};
const headers = {};
Object.keys(rawHeaders).forEach(function (k) { headers[k.toLowerCase()] = rawHeaders[k]; });

function reject(status, reason) {
  return [{ json: { accepted: false, httpStatus: status, response: { error: status === 401 ? 'unauthorized' : 'rejected', reason: reason }, envBlocked: read.blocked }, pairedItem: { item: 0 } }];
}

let cfg;
try { cfg = parseConfig(env); } catch (err) { return reject(500, 'config_error: ' + err.message); }

let rawBody = null;
try {
  const buffer = await this.helpers.getBinaryDataBuffer(0, 'data');
  rawBody = buffer.toString('utf8');
} catch (err) {
  rawBody = null;
}

if (cfg.requireSignature) {
  if (rawBody === null) return reject(400, 'raw_body_unavailable_enable_the_webhook_raw_body_option');
  const secret = cfgUnset(env.WEBHOOK_SIGNING_SECRET) ? null : String(env.WEBHOOK_SIGNING_SECRET).trim();
  let crypto;
  try { crypto = require('crypto'); } catch (err) { return reject(500, 'crypto_builtin_not_allowed_set_NODE_FUNCTION_ALLOW_BUILTIN_crypto'); }
  const now = Date.now();
  const check = cfg.signatureMode === 'hubspot_v3'
    ? verifyHubSpotV3Signature('POST', cfg.webhookPublicUrl, rawBody, headers['x-hubspot-signature-v3'], headers['x-hubspot-request-timestamp'], secret, now, cfg.signatureToleranceSeconds,
        function (s, m) { return crypto.createHmac('sha256', s).update(m, 'utf8').digest('base64'); })
    : verifyHmacSignature(rawBody, headers['x-signature'], headers['x-signature-timestamp'], secret, now, cfg.signatureToleranceSeconds,
        function (s, m) { return crypto.createHmac('sha256', s).update(m, 'utf8').digest('hex'); });
  if (!check.ok) return reject(401, check.reason);
}

let payload;
if (rawBody !== null) {
  try { payload = JSON.parse(rawBody); } catch (err) { return reject(400, 'invalid_json'); }
} else {
  payload = input.json ? input.json.body : null;
}

let rules;
let rulesSource;
if (!cfgUnset(env.MARGIN_RULES_JSON)) {
  try { rules = JSON.parse(String(env.MARGIN_RULES_JSON)); } catch (err) { return reject(500, 'margin_rules_json_invalid'); }
  rulesSource = 'MARGIN_RULES_JSON';
} else if (!cfg.writesEnabled) {
  rules = EXAMPLE_RULES;
  rulesSource = 'embedded_example_rules_dry_run_only';
} else {
  return reject(500, 'margin_rules_not_configured_set_MARGIN_RULES_JSON');
}
const ruleCheck = validateRules(rules);
if (!ruleCheck.ok) return reject(500, 'margin_rules_invalid: ' + ruleCheck.errors.join('; '));

const extracted = extractDealEvents(payload, cfg);
return [{
  json: {
    accepted: true,
    httpStatus: 202,
    response: { accepted: extracted.deals.length, ignored: extracted.ignored.length, writeMode: cfg.writeMode },
    cfg: cfg,
    rules: rules,
    rulesSource: rulesSource,
    rulesWarnings: ruleCheck.warnings,
    deals: extracted.deals,
    ignored: extracted.ignored,
    envBlocked: read.blocked
  },
  pairedItem: { item: 0 }
}];
`);

